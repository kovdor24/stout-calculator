-- Имя автора в сообщении администрации.
--
-- Наблюдателям разрешили отвечать монтажникам, и стало непонятно, кто именно
-- написал: у монтажника любое письмо подписано «Администратор», а в панели
-- управления исходящие сообщения выглядят как «Вы» у всех, кто их видит.
-- Узнать имя по sender_id монтажник не может — чужие строки таблицы users
-- ему не отдаются, поэтому имя кладём в само сообщение.
--
-- Заполняется только когда отвечает наблюдатель (см. sendAdminMessage в app.js):
-- письма владельца и администраторов по-прежнему подписаны «Администратор»,
-- и старые сообщения, где колонка пустая, выглядят как раньше.
--
-- Выполнить вручную в Supabase SQL Editor (весь файл целиком, за один раз).

alter table public.messages add column if not exists sender_name text;
