-- Настройки учётной записи монтажника, включая реквизиты компании.
--
-- Раньше реквизиты (название, сайт, адрес, банк, логотип) лежали внутри самой
-- сметы — в calc_data.customCompany. Из-за этого открытие любого сохранённого
-- расчёта или загрузка КП по номеру подставляли реквизиты того расчёта, а
-- «Сбросить всё» и выход из аккаунта стирали их совсем: монтажники жаловались,
-- что свои реквизиты «невозможно сохранить, всё время возвращается ТЕРЕМ».
--
-- Теперь это настройка учётной записи. Хранится в том же JSONB, что и личный
-- прайс-лист монтажных работ со своим оборудованием:
--
--   installer_settings = {
--     "company":          { "name", "website", "address", "bank", "logo" },
--     "workPrices":       { "<название работы>": <цена> },
--     "equipmentLibrary": [...],
--     "swapLog":          [...],
--     "deletionLog":      [...]
--   }
--
-- Колонка могла быть заведена вручную раньше, когда делались вкладки личного
-- кабинета, — поэтому if not exists. Выполнить в Supabase SQL Editor ДО выкладки:
-- без неё реквизиты будут жить только в браузере и пропадут при выходе из аккаунта
-- (сайт это переживёт — синхронизация молча отключится, — но смысл правки теряется).

alter table public.users
    add column if not exists installer_settings jsonb;
