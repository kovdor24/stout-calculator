--
-- В первой версии списка (20260816_add_analytics_chart_brands.sql) кириллица
-- была заведена не всем: «тим» я пропустил, потому что это обычное слово и в
-- счёт марки попадает посторонний спрос. Ошибка не в оценке шума, а в том, что
-- из-за неё семь марок мерились двумя написаниями, а TIM — одним, и линии
-- перестали быть сравнимы между собой. Перекос в методике хуже шума: шум
-- видно и о нём можно спорить, а разное правило для разных марок незаметно.
--
-- Поэтому: одинаково всем, а решение «это слово приносит мусор» принимается
-- потом и по каждому слову отдельно — галочкой в дашборде, уже глядя на цифры.
--
-- Написания к выключенным маркам (uponor, usystems, oventrop) заводим тоже:
-- своей линии они не дают, пока цель выключена, зато при включении сравнение
-- сразу корректное, без ожидания ещё одного прогона Wordstat.
--
-- Выполнить вручную в Supabase SQL Editor, весь файл целиком.

