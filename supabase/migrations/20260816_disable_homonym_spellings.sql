-- Написания-омонимы выключаем по правилу, а не по вкусу.
--
-- Правило: если кириллическое написание набирает больше чем вдвое против
-- латинского, это не марка, а совпадение слов. У настоящей транслитерации
-- отношение всегда меньше единицы — по-русски марку ищут реже, чем латиницей.
-- Замеры 16.08.2026, последний закрытый месяц 2026-07:
--
--   эльзен ×0,002   виеир ×0,02   роммер ×0,20   юсистемс ×0,21
--   валфекс ×0,23   овентроп ×0,46   валтек ×0,53   упонор ×0,66
--   стаут ×1,04  |  рехау ×3,0   тим ×16,0
--
-- «тим» — 2,4 млн запросов при 151 тыс. у латинского tim: слово ловит имена и
-- всё прочее, к марке отношения не имеющее. «рехау» — 146 тыс. против 49 тыс.:
-- по-русски REHAU ищут как оконный профиль, а не как трубу.
--
-- Важно, что правило одно для всех марок и проверяется числом: новое написание
-- проверяется им же, без отдельного разбирательства. Спрос по выключенным
-- словам продолжает собираться — вернуть их можно галочкой в дашборде, и
-- история при этом не потеряется.
--
-- Выполнить вручную в Supabase SQL Editor.

update public.analytics_chart_brands
   set enabled = false, updated_at = now()
 where word in ('тим', 'рехау');
