-- Supabase по умолчанию даёт EXECUTE на ВСЕ функции схемы public ролям anon
-- и authenticated, если явно не отозвать. Часть geймификационных функций
-- задумывались как внутренние примитивы (их должны звать только другие
-- SECURITY DEFINER функции изнутри), но по факту оказались вызываемыми
-- напрямую с anon-ключом кем угодно, в обход всех проверок:
--
--   grm_award_xp()       — принимает p_user_id и p_amount без каких-либо
--                          проверок личности/региона внутри себя. Позволяет
--                          начислить (или списать, отрицательным p_amount)
--                          произвольное число очков ЛЮБОМУ пользователю.
--   grm_monthly_rollover() — резервируется только для cron (pg_cron), но
--                          при прямом вызове может преждевременно обнулить
--                          месячный счёт всем и выдать значок «Лидер месяца»
--                          не в срок.
--
-- grm_track_action / grm_unlock_achievement / grm_leaderboard* / grm_prize_*
-- НЕ трогаем — они специально сделаны вызываемыми с фронта и сами проверяют
-- авторизацию (grm_current_user_id()) и регион (grm_is_eligible_region())
-- изнутри, прежде чем что-либо делать.
--
-- SECURITY DEFINER функции продолжают работать друг из друга без каких-либо
-- прав — вызов функции ИЗ ДРУГОЙ функции идёт напрямую, минуя проверку
-- GRANT/REVOKE, которая применяется только к внешнему вызову через RPC/REST.
--
-- Выполнить вручную в Supabase SQL Editor ПОСЛЕ 20260717/18/19/20_....sql,
-- целиком за один раз.
-- ============================================================================

revoke execute on function public.grm_award_xp(uuid, text, integer, text) from public, anon, authenticated;
revoke execute on function public.grm_monthly_rollover() from public, anon, authenticated;
